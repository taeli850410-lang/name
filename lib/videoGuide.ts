export const AUDIENCES: Audience[] = ["tenant", "buyer", "investor"];

/** 0~5 를 사람 말로. 화면에 숫자만 있으면 그게 몇 점 만점인지 아무도 모릅니다 */
export function impactLabel(level: number): string {
  if (level >= 4) return "높음";
  if (level >= 2) return "보통";
  return "낮음";
}

/** 주제 × 부류 영향도. 이미 '그래서 내 부동산에는?'을 그리는 표를 그대로 씁니다 */
export function audienceImpact(topic: Topic, who: Audience): number {
  return Math.max(...AUDIENCE_PERSONAS[who].map((p) => PERSONA_MATRIX[topic][p] ?? 0));
}

